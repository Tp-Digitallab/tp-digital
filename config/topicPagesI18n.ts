export function getTopicPage(slug: string, lang: Lang): TopicPageData {
  const base = topicPages[slug];
  if (lang === "de") return base;
  const o = (lang === "en" ? en : ru)[slug];
  if (!o) return base;
  return {
    ...base,
    ...o,
    demo: base.demo && o.demo ? { ...base.demo, ...o.demo } : base.demo,
    demo2: base.demo2 && o.demo2 ? { ...base.demo2, ...o.demo2 } : base.demo2,
  };
}
